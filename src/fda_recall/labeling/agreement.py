"""Inter-annotator agreement between LLM annotators A (gold_v1) and B (relabel of 60) (T3.1.3).

    python -m fda_recall.labeling.agreement   -> reports/labeling_agreement.md + metrics labels.*
"""
from __future__ import annotations

import hashlib
from pathlib import Path

import pandas as pd
from sklearn.metrics import cohen_kappa_score

from ..metrics import record_metric

ROOT = Path(__file__).resolve().parents[3]
GOLD = ROOT / "data" / "labels" / "gold_v1.csv"
RELABEL = ROOT / "data" / "labels" / "gold_v1_relabel.csv"
REPORT = ROOT / "reports" / "labeling_agreement.md"
SRC = "labeling/agreement.py"


def agreement(a: pd.Series, b: pd.Series) -> tuple[float, float]:
    return float(cohen_kappa_score(a, b)), float((a.to_numpy() == b.to_numpy()).mean())


def main() -> int:
    gold = pd.read_csv(GOLD, dtype={"event_id": str})
    rel = pd.read_csv(RELABEL, dtype={"event_id": str})
    m = rel.merge(gold[["event_id", "label"]], on="event_id", suffixes=("_b", "_a"), validate="one_to_one")
    assert len(m) == len(rel), "every relabeled event must exist in the gold set"
    kappa, raw = agreement(m["label_a"], m["label_b"])
    sha = hashlib.sha256(GOLD.read_bytes()).hexdigest()
    record_metric("labels.n_gold", int(len(gold)), SRC)
    record_metric("labels.kappa_llm_a_vs_b", round(kappa, 4), SRC, note=f"two LLM annotators, n={len(m)}")
    record_metric("labels.gold_sha256", sha, SRC)
    dis = m[m["label_a"] != m["label_b"]]
    L = ["# Labeling Agreement (T3.1.3; generated by `python -m fda_recall.labeling.agreement`)", "",
         "Two **LLM annotators** (not human): A = Claude Opus 5.5 labeled all 300 events; B = an independent session "
         "given only the taxonomy and labeling guide, blind to A's labels, labeled a random 60 (seed 7).", "",
         f"- Cohen's kappa (primary label): **{kappa:.3f}** (target >= 0.75)",
         f"- Raw agreement: {raw:.1%} ({int(raw * len(m))}/{len(m)})",
         f"- Gold labels frozen: `data/labels/gold_v1.csv` sha256 `{sha}`", "",
         "Limitations: both annotators are the same model family and share the written guide, so agreement can "
         "overstate accuracy (shared systematic errors are invisible). Annotator A also authored the keyword baseline "
         "rules. A human spot check is recommended before external use.", "",
         "## Disagreements", "", "| event_id | A | B | text |", "|---|---|---|---|"]
    L += [f"| {r.event_id} | {r.label_a} | {r.label_b} | {str(r.reason_text)[:120]} |" for r in dis.itertuples()]
    REPORT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"kappa {kappa:.4f}, raw {raw:.3f}, n {len(m)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
