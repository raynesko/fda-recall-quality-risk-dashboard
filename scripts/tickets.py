#!/usr/bin/env python
"""Ticket CLI. Source of truth = tickets/<sub-epic>/T*.md (YAML-ish frontmatter).

Usage (run from repo root, stdlib only):
  python scripts/tickets.py list [--status todo] [--week 3] [--priority P0]
  python scripts/tickets.py next            # next unblocked ticket (week, then priority, then ID)
  python scripts/tickets.py show T2.1.2
  python scripts/tickets.py set T2.1.2 in_progress|done|blocked|todo
  python scripts/tickets.py check T2.1.2 2  # tick acceptance criterion #2 (1-based)
  python scripts/tickets.py index           # regenerate tickets/INDEX.md and tickets/tickets.csv
"""
from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TDIR = ROOT / "tickets"
STATUSES = {"todo", "in_progress", "done", "blocked"}


def parse(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    m = re.match(r"---\n(.*?)\n---\n(.*)", text, re.S)
    if not m:
        raise ValueError(f"{path}: missing frontmatter")
    meta: dict = {}
    for line in m.group(1).splitlines():
        k, _, v = line.partition(": ")
        v = v.strip()
        if v.startswith("[") and v.endswith("]"):
            meta[k] = [x.strip() for x in v[1:-1].split(",") if x.strip()]
        else:
            meta[k] = v
    meta["_path"], meta["_body"] = path, m.group(2)
    return meta


def load() -> list[dict]:
    ts = [parse(p) for p in sorted(TDIR.glob("SE*/T*.md"))]
    return sorted(ts, key=lambda t: (int(t["week"]), t["priority"], idkey(t["id"])))


def idkey(i: str):
    return [int(x) for x in i.lstrip("T").split(".")]


def section(body: str, name: str) -> str:
    m = re.search(rf"## {name}\n(.*?)(?=\n## |\Z)", body, re.S)
    return m.group(1).strip() if m else ""


def set_field(path: Path, key: str, value: str) -> None:
    text = path.read_text(encoding="utf-8")
    text = re.sub(rf"^{key}: .*$", f"{key}: {value}", text, count=1, flags=re.M)
    path.write_text(text, encoding="utf-8")


def unblocked(t: dict, by_id: dict) -> bool:
    return all(by_id[d]["status"] == "done" for d in t.get("depends_on", []) if d in by_id)


def cmd_index(ts: list[dict]) -> None:
    lines = ["# Ticket Index", "", "_Generated by `python scripts/tickets.py index`. Do not edit by hand._", ""]
    lines += ["| ID | Title | Type | Pri | Est (h) | Week | Status | Depends on |", "|---|---|---|---|---|---|---|---|"]
    for t in sorted(ts, key=lambda t: idkey(t["id"])):
        rel = t["_path"].relative_to(TDIR).as_posix()
        lines.append(
            f"| [{t['id']}]({rel}) | {t['title']} | {t['type']} | {t['priority']} | {t['estimate_hours']} "
            f"| {t['week']} | {t['status']} | {', '.join(t.get('depends_on', [])) or '-'} |"
        )
    core = [t for t in ts if t["priority"] != "P2"]
    lines += ["", f"Core (P0/P1) hours: {sum(float(t['estimate_hours']) for t in core):.1f}  |  "
              f"Stretch (P2) hours: {sum(float(t['estimate_hours']) for t in ts if t['priority'] == 'P2'):.1f}"]
    (TDIR / "INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    cols = ["ID", "Title", "Type", "Epic", "Sub-epic", "Story", "Priority", "Estimate (h)", "Size",
            "Week", "Status", "Depends on", "Deliverable", "Description", "Acceptance criteria"]
    with open(TDIR / "tickets.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(cols)
        for t in sorted(ts, key=lambda t: idkey(t["id"])):
            w.writerow([t["id"], t["title"], t["type"], t["epic"], t["sub_epic"], t["story"], t["priority"],
                        t["estimate_hours"], t["size"], t["week"], t["status"], ";".join(t.get("depends_on", [])),
                        t["deliverable"], section(t["_body"], "Description"),
                        section(t["_body"], "Acceptance criteria")])
    print(f"wrote {TDIR/'INDEX.md'} and tickets.csv ({len(ts)} tickets)")


def main(argv: list[str]) -> int:
    if not argv:
        print(__doc__)
        return 1
    ts = load()
    by_id = {t["id"]: t for t in ts}
    cmd = argv[0]
    if cmd == "list":
        opts = dict(zip(argv[1::2], argv[2::2]))
        for t in ts:
            if opts.get("--status") not in (None, t["status"]):
                continue
            if opts.get("--week") not in (None, t["week"]):
                continue
            if opts.get("--priority") not in (None, t["priority"]):
                continue
            print(f"{t['id']:8} W{t['week']} {t['priority']} {t['estimate_hours']:>4}h {t['status']:11} {t['title']}")
    elif cmd == "next":
        busy = [t for t in ts if t["status"] == "in_progress"]
        if busy:
            print("IN PROGRESS:", ", ".join(t["id"] for t in busy))
        cands = [t for t in ts if t["status"] == "todo" and t["priority"] != "P2" and unblocked(t, by_id)]
        if not cands:
            print("No unblocked core tickets (done, or blocked by in-progress work).")
            return 0
        t = cands[0]
        print(f"NEXT: {t['id']} - {t['title']}\nFile: {t['_path']}")
    elif cmd == "show":
        print(by_id[argv[1]]["_path"].read_text(encoding="utf-8"))
    elif cmd == "set":
        tid, status = argv[1], argv[2]
        assert status in STATUSES, f"status must be one of {STATUSES}"
        if status in ("in_progress", "done"):
            missing = [d for d in by_id[tid].get("depends_on", []) if by_id[d]["status"] != "done"]
            if missing:
                print(f"Refusing: {tid} depends on unfinished {missing}")
                return 2
        if status == "done" and "- [ ]" in by_id[tid]["_body"]:
            print(f"Refusing: {tid} has unchecked acceptance criteria. Verify, then use `check`.")
            return 2
        set_field(by_id[tid]["_path"], "status", status)
        cmd_index(load())
    elif cmd == "check":
        p = by_id[argv[1]]["_path"]
        n, seen, out = int(argv[2]), 0, []
        for line in p.read_text(encoding="utf-8").splitlines():
            if line.startswith("- [ ] ") or line.startswith("- [x] "):
                seen += 1
                if seen == n:
                    line = "- [x] " + line[6:]
            out.append(line)
        p.write_text("\n".join(out) + "\n", encoding="utf-8")
    elif cmd == "index":
        cmd_index(ts)
    else:
        print(__doc__)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
